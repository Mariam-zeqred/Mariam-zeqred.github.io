"""Refresh data/repos.js from the public repositories of github.com/Mariam-zeqred.

Run daily by .github/workflows/sync-repos.yml (and by hand with `python3 scripts/sync_repos.py`).
The page merges this file over data/content.js: a project card is shown only when its
repository is actually public, placeholder summaries are replaced by the repository's own
README introduction, topics become tags, and courses show how many chapters exist so far.
Public repositories that have no hand-written entry get an automatic card.
"""
from __future__ import annotations

import base64, datetime as dt, json, os, re, sys, urllib.request

OWNER = "Mariam-zeqred"
SKIP = {OWNER, f"{OWNER}.github.io"}  # profile README repo and this site
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "repos.js")
API = "https://api.github.com"
HEADERS = {"Accept": "application/vnd.github+json", "User-Agent": "mariam-site-sync"}
if os.environ.get("GITHUB_TOKEN"):
    HEADERS["Authorization"] = "Bearer " + os.environ["GITHUB_TOKEN"]


def get(url):
    req = urllib.request.Request(url, headers=HEADERS)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())


def readme_intro(full_name: str) -> str:
    """First real paragraph of the README, as plain text (links -> their text, no badges/code)."""
    try:
        data = get(f"{API}/repos/{full_name}/readme")
        md = base64.b64decode(data["content"]).decode("utf-8", "replace")
    except Exception:
        return ""
    md = re.sub(r"```.*?```", "", md, flags=re.S)
    for para in re.split(r"\n\s*\n", md):
        p = para.strip()
        if not p or p.startswith("#") or p.startswith("[![") or p.startswith("!") or p.startswith("|") or p.startswith(">"):
            continue
        p = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", p)
        p = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", p)
        p = re.sub(r"[*_`]", "", p)
        p = re.sub(r"\s+", " ", p).strip()
        if len(p) > 60:
            return p[:600]
    return ""


def chapter_count(full_name: str) -> int:
    try:
        tree = get(f"{API}/repos/{full_name}/contents/")
    except Exception:
        return 0
    names = [t["name"] for t in tree if t["type"] == "file"]
    return sum(1 for n in names if re.match(r"(ch\d{2}|lesson\d+)-.*\.md$", n))


def main():
    repos = get(f"{API}/users/{OWNER}/repos?per_page=100&type=public&sort=pushed")
    out = {}
    for r in repos:
        if r["name"] in SKIP or r.get("fork"):
            continue
        full = r["full_name"]
        out[r["name"]] = {
            "url": r["html_url"],
            "description": r.get("description") or "",
            "topics": r.get("topics") or [],
            "language": r.get("language") or "",
            "pushedAt": r["pushed_at"][:10],
            "createdAt": r["created_at"][:10],
            "stars": r.get("stargazers_count", 0),
            "intro": readme_intro(full),
            "chapters": chapter_count(full),
        }
    js = ("// Generated by scripts/sync_repos.py - do not edit by hand. Public repositories of " + OWNER + ".\n"
          "window.REPOS = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"
          "window.REPOS_UPDATED = " + json.dumps(dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d")) + ";\n")
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if old.split("window.REPOS_UPDATED")[0] == js.split("window.REPOS_UPDATED")[0]:
        print("no change:", len(out), "public repositories")
        return 0
    open(OUT, "w", encoding="utf-8", newline="\n").write(js)
    print("updated:", ", ".join(sorted(out)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
